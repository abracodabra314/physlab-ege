#pragma once

#include <QString>

namespace lab::utils {

/**
 * Преобразует компактную математическую разметку в HTML для QLabel (Qt Rich Text).
 *
 * Поддерживаемые элементы:
 *   \frac{a}{b}      — дробь (числитель над знаменателем, разделитель — черта);
 *   x_{1} x^{2}      — подстрочные и надстрочные индексы;
 *   \sqrt{a}         — квадратный корень;
 *   \cdot \approx \Rightarrow \le \ge \ne \pi \Delta ... — символы;
 *   \text{...}       — обычный текст внутри формулы;
 *   \*               — экранирование спецсимвола (* — любой из \ { } [ ] _ ^).
 *
 * Остальной текст (в том числе кириллица в UTF-8) передаётся как есть,
 * символы <, >, & экранируются для HTML.
 */
QString toRichMath(const QString& source);

/**
 * То же, что и toRichMath, но результат оборачивается в <div align="center"> —
 * удобно для строк формул.
 */
QString toRichMathLine(const QString& source);

/**
 * Аккуратное форматирование числа: дробная часть отбрасывается, если число целое;
 * используется десятичная запятая; лишние нули убираются; применяется
 * разумное количество значащих знаков (precision — количество знаков после точки).
 */
QString formatNumber(double value, int precision = 3);

/** Форматирование длительности модельного времени: 2.35 -> «2 ч 21 мин» (часы) или «3 мин 30 с» (секунды). */
QString formatDuration(double amount, const QString& unit);

}  // namespace lab::utils
